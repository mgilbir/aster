//go:build ignore

// zonenames_gen makes zonenames_table.go from V8's zone names, recorded by
// testdata/gen_zonenames.mjs (samples mode), read against the tzdata release
// node's ICU carries (internal/nodetz), whatever the host's:
//
//	node testdata/gen_zonenames.mjs ../nodetz/tzdata.zi samples > /tmp/samples.json
//	go run zonenames_gen.go /tmp/samples.json
//
// V8 prints ICU's long name of a zone's current metazone, the daylight one
// when its DST flag is set. Each name of tzdata has at most two: they are
// told apart by the release's IsDST at the instants they were printed. ICU
// flags a few offsets as daylight that tzdata calls standard (a zone that
// kept its summer offset all year from some date on, e.g. America/Vancouver
// from November 2026, which CLDR still files under its old metazone): such a
// run, to the end of the samples, is recorded as daylightFrom. A name whose
// offsets in node are not the release's is one node did not resolve from TZ
// (the recorder hides the host's zoneinfo, and without a file of that name
// node gives offset 0 and never sets the DST flag, for TZ=CET, Cuba, EET,
// EST, HST, Iran, MET, MST, PRC, ROC, ROK and W-SU, though it names them): it
// is a link, and takes its target's names. Any other disagreement stops the
// generator.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"time"

	"github.com/mgilbir/aster/internal/nodetz"
)

type sample struct {
	t    int64
	name string
}

func main() {
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		panic(err)
	}
	var doc struct {
		Node, TZ string
		Zones    map[string][][3]any
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		panic(err)
	}
	nameIdx := map[string]int{}
	var names []string
	idx := func(n string) int {
		if i, ok := nameIdx[n]; ok {
			return i
		}
		nameIdx[n] = len(names)
		names = append(names, n)
		return len(names) - 1
	}
	type entry struct {
		std, dst     int
		daylightFrom int64
	}
	if doc.TZ != nodetz.Version() {
		panic(fmt.Sprintf("the samples are of tzdata %s, internal/nodetz of %s", doc.TZ, nodetz.Version()))
	}
	zi, err := os.ReadFile("../nodetz/tzdata.zi")
	if err != nil {
		panic(err)
	}
	links := map[string]string{} // tzdata.zi's lines: "L TARGET NAME"
	for _, l := range strings.Split(string(zi), "\n") {
		if f := strings.Split(l, " "); len(f) == 3 && f[0] == "L" {
			links[f[2]] = f[1]
		}
	}
	var skipped, unresolved []string
	zones := map[string]entry{}
	var keys []string
	var all []string
	for z := range doc.Zones {
		all = append(all, z)
	}
	sort.Strings(all)
	for _, z := range all {
		rows := doc.Zones[z]
		loc, err := nodetz.Load(z)
		if err != nil {
			panic(err)
		}
		resolved := true
		for _, r := range rows {
			if _, off := time.UnixMilli(int64(r[0].(float64))).In(loc).Zone(); float64(-off/60) != r[2].(float64) {
				resolved = false
			}
		}
		if !resolved {
			unresolved = append(unresolved, z)
			continue
		}
		count := map[bool]map[string]int{false: {}, true: {}}
		ss := make([]sample, len(rows))
		for i, r := range rows {
			ss[i] = sample{int64(r[0].(float64)), r[1].(string)}
			count[time.UnixMilli(ss[i].t).In(loc).IsDST()][ss[i].name]++
		}
		pick := func(m map[string]int) string {
			best, n := "", -1
			for k, c := range m {
				if c > n || c == n && k < best {
					best, n = k, c
				}
			}
			return best
		}
		std, dst := pick(count[false]), pick(count[true])
		if std == "" {
			std = dst
		}
		if dst == "" {
			dst = std
		}
		e := entry{std: idx(std), dst: idx(dst)}
		// Disagreements: ICU's daylight where tzdata says standard, to the
		// end of the samples. Any other pattern (a legacy name ICU keeps as
		// a zone of its own, as "EET" and "Eire") leaves the name out: its
		// dates print tzdata's abbreviation.
		first, ok := -1, true
		for i, s := range ss {
			isDST := time.UnixMilli(s.t).In(loc).IsDST()
			want := std
			if isDST {
				want = dst
			}
			switch {
			case s.name == want && first < 0:
			case s.name != want && !isDST && s.name == dst && i > 0:
				if first < 0 {
					first = i
				}
			default:
				ok = false
			}
		}
		if !ok {
			skipped = append(skipped, z)
			continue
		}
		if first >= 0 {
			// The run began at the tzdata transition before its first sample.
			at := func(t int64) string {
				n, off := time.UnixMilli(t).In(loc).Zone()
				return fmt.Sprint(n, off)
			}
			lo, hi := ss[first-1].t, ss[first].t
			for hi-lo > 1 {
				if mid := lo + (hi-lo)/2; at(mid) == at(hi) {
					hi = mid
				} else {
					lo = mid
				}
			}
			e.daylightFrom = hi
		}
		zones[z] = e
		keys = append(keys, z)
	}
	for _, z := range unresolved {
		e, ok := zones[links[z]]
		if !ok {
			panic(fmt.Sprintf("%s: node's offsets are not tzdata's, and it is not a link to a recorded zone", z))
		}
		zones[z] = e
		keys = append(keys, z)
	}
	sort.Strings(keys)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by zonenames_gen.go from V8's zone names (node %s, tzdata %s); DO NOT EDIT.\n\n", doc.Node, doc.TZ)
	b.WriteString("package format\n\n// zoneLongNames are ICU's long metazone names V8 prints (zoneNameTable's indexes).\nvar zoneLongNames = [...]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	b.WriteString("}\n\n// zoneNameTable maps each tzdata name to its standard and daylight names.\nvar zoneNameTable = map[string]zoneName{\n")
	for _, z := range keys {
		e := zones[z]
		fmt.Fprintf(&b, "\t%q: {%d, %d, %d},\n", z, e.std, e.dst, e.daylightFrom)
	}
	b.WriteString("}\n")
	sort.Strings(skipped)
	fmt.Fprintf(&b, "\n// Left out (ICU keeps them as zones of their own, unlike tzdata's links): %q\n", skipped)
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("zonenames_table.go", src, 0o644); err != nil {
		panic(err)
	}
}
