package jsmath

import (
	"math"
	"testing"
)

// The expected values are node's `x | 0` and `x >>> 0`.
func TestToInt32(t *testing.T) {
	for _, tc := range []struct {
		x   float64
		i32 int32
		u32 uint32
	}{
		{0, 0, 0},
		{math.Copysign(0, -1), 0, 0},
		{0.9, 0, 0},
		{-0.9, 0, 0},
		{1.5, 1, 1},
		{-1.5, -1, 4294967295},
		{2147483647, 2147483647, 2147483647},
		{2147483647.9, 2147483647, 2147483647},
		{2147483648, -2147483648, 2147483648},
		{-2147483648, -2147483648, 2147483648},
		{-2147483648.9, -2147483648, 2147483648},
		{-2147483649, 2147483647, 2147483647},
		{4294967295, -1, 4294967295},
		{4294967296, 0, 0},
		{4294967296.5, 0, 0},
		{4294967297, 1, 1},
		{-4294967297, -1, 4294967295},
		{10000000000, 1410065408, 1410065408},
		{-10000000000, -1410065408, 2884901888},
		{9007199254740991, -1, 4294967295},
		{9007199254740992, 0, 0},
		{9223372036854775807, 0, 0},
		{9223372036854777856, 2048, 2048},
		{-9223372036854775808, 0, 0},
		{1e19, -1981284352, 2313682944},
		{1e20, 1661992960, 1661992960},
		{-1e20, -1661992960, 2632974336},
		{1.7976931348623157e+308, 0, 0},
		{-1.7976931348623157e+308, 0, 0},
		{5e-324, 0, 0},
		{math.NaN(), 0, 0},
		{math.Inf(1), 0, 0},
		{math.Inf(-1), 0, 0},
		{123456789012.75, -1097262572, 3197704724},
		{3.4e+38, 0, 0},
	} {
		if got := ToInt32(tc.x); got != tc.i32 {
			t.Errorf("ToInt32(%v) = %d, want %d", tc.x, got, tc.i32)
		}
		if got := ToUint32(tc.x); got != tc.u32 {
			t.Errorf("ToUint32(%v) = %d, want %d", tc.x, got, tc.u32)
		}
	}
}
